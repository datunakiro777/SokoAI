"""Export the small pilot CNN for the JavaScript-only Expo Go preview.

The resulting model is an experimental species demonstrator. It must never
enable an edible verdict or be used as a commercial safety model.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import torch


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--metadata", required=True)
    parser.add_argument("--mobile-dir", default="mobile")
    args = parser.parse_args()

    mobile = Path(args.mobile_dir)
    metadata = json.loads(Path(args.metadata).read_text(encoding="utf-8"))
    if metadata.get("backbone") != "small_cnn" or metadata.get("releaseGatePassed") is not False:
        raise SystemExit("Only the unvalidated small CNN may be exported as a pilot preview")

    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    weights = {
        key.removeprefix("network."): value.detach().cpu().numpy()
        for key, value in checkpoint["state_dict"].items()
        if key.startswith("network.")
    }
    parts: list[np.ndarray] = []

    def add(key: str) -> dict[str, int]:
        array = np.asarray(weights[key], dtype="<f4").reshape(-1)
        offset = sum(part.size for part in parts)
        parts.append(array)
        return {"offset": offset, "length": int(array.size)}

    layers = []
    input_channels = 3
    for conv_index, norm_index, output_channels in zip(
        (0, 3, 6, 9, 12), (1, 4, 7, 10, 13), (32, 64, 128, 192, 256)
    ):
        layers.append({
            "inputChannels": input_channels,
            "outputChannels": output_channels,
            "conv": add(f"features.{conv_index}.weight"),
            "gamma": add(f"features.{norm_index}.weight"),
            "beta": add(f"features.{norm_index}.bias"),
        })
        input_channels = output_channels

    heads = {
        name: {"weight": add(f"{name}.weight"), "bias": add(f"{name}.bias")}
        for name in ("presence", "toxic", "species")
    }
    blob = np.concatenate(parts).astype("<f4", copy=False)
    assets = mobile / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "pilot-weights.bin").write_bytes(blob.tobytes())

    catalog = {
        "modelVersion": metadata["modelVersion"],
        "species": metadata["species"],
        "layers": layers,
        "heads": heads,
        "floatCount": int(blob.size),
        "releaseGatePassed": False,
    }
    source = (
        "// Generated by ml/export_expo_preview.py. Experimental preview only.\n"
        "import type { Species } from './decision';\n"
        "import type { PilotModelSpec } from './pilotCnn';\n"
        "// eslint-disable-next-line @typescript-eslint/no-require-imports\n"
        "export const pilotWeightsAsset: number = require('../../assets/pilot-weights.bin');\n"
        "export const pilotModel: PilotModelSpec & { species: Species[]; modelVersion: string; "
        "releaseGatePassed: false } = "
        + json.dumps(catalog, ensure_ascii=False, indent=2)
        + ";\n"
    )
    (mobile / "src" / "lib" / "pilotModelBundle.ts").write_text(source, encoding="utf-8")
    print(f"Exported {blob.nbytes} bytes for Expo Go pilot preview")


if __name__ == "__main__":
    main()
