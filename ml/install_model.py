"""Package a validated ONNX model with the app; preview installs cannot enable edible verdicts."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model-dir", required=True)
    parser.add_argument("--report", required=True)
    parser.add_argument("--mobile-dir", default="mobile")
    parser.add_argument("--preview", action="store_true", help="Install model with likely-edible output disabled")
    args = parser.parse_args()
    model_dir = Path(args.model_dir)
    repository = Path(__file__).resolve().parents[1]
    mobile = Path(args.mobile_dir)
    model = model_dir / "vision.onnx"
    metadata_path = model_dir / "metadata.json"
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    report = json.loads(Path(args.report).read_text(encoding="utf-8"))
    if report.get("model_sha256") != digest(model) or report.get("metadata_sha256") != digest(metadata_path):
        raise SystemExit("Evaluation report does not match the model and metadata")
    for report_key, source in {
        "decision_sha256": repository / "ml" / "safety.py",
        "mobile_decision_sha256": mobile / "src" / "lib" / "decision.ts",
        "mobile_inference_sha256": mobile / "src" / "lib" / "inference.ts",
    }.items():
        if report.get(report_key) != digest(source):
            raise SystemExit(f"Evaluation report does not match {source}; run a new independent evaluation")
    if not args.preview and report.get("gate_passed") is not True:
        raise SystemExit("False-safe release gate has not passed; use --preview for a non-edible development build")
    metadata["releaseGatePassed"] = not args.preview
    (mobile / "assets").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(model, mobile / "assets" / "vision.onnx")
    generated = (
        "// Generated by ml/install_model.py. Do not edit by hand.\n"
        "import type { Species } from './decision';\n"
        "export const modelAsset: number = require('../../assets/vision.onnx');\n"
        "export const modelMetadata: { modelVersion: string; species: Species[]; presenceTemperature: number; "
        "toxicTemperature: number; speciesTemperature: number; releaseGatePassed: boolean } = "
        + json.dumps(metadata, ensure_ascii=False, indent=2) + ";\n"
    )
    (mobile / "src" / "lib" / "modelBundle.ts").write_text(generated, encoding="utf-8")
    print("Installed model into mobile app", "(preview only)" if args.preview else "(release gate passed)")


if __name__ == "__main__":
    main()
